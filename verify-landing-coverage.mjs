import fs from 'node:fs';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(new URL('./render-app/package.json',import.meta.url));
const ts=require('typescript'),React=require('react'),{renderToStaticMarkup}=require('react-dom/server');
const module={exports:{}};
const source=fs.readFileSync('components/landing-intro.tsx','utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText;
new Function('require','module','exports',code)(require,module,module.exports);
const {LandingCoverage}=module.exports;
const states=[{sigla:'PR',nome:'Paraná'},{sigla:'SC',nome:'Santa Catarina'},{sigla:'RJ',nome:'Rio de Janeiro'}];
const render=status=>renderToStaticMarkup(React.createElement(LandingCoverage,{states,statesStatus:status,onRetryStates:()=>{}}));
const ready=render('ready');
assert.ok(ready.includes('Sem conexão gov.br'));
assert.ok(ready.includes('Conexão gov.br necessária'));
assert.ok(ready.includes('Além da conta do Preço Perto'));
const list=ready.match(/<ul[\s\S]*?<\/ul>/)[0];
assert.ok(!list.includes('Paraná'));assert.ok(list.includes('Rio de Janeiro'));assert.ok(list.includes('Santa Catarina'));
assert.ok(list.indexOf('Rio de Janeiro')<list.indexOf('Santa Catarina'));
assert.ok(render('loading').includes('Carregando estados participantes'));
assert.ok(!render('loading').includes('<ul'));
assert.ok(render('error').includes('Tentar novamente'));assert.ok(!render('error').includes('<ul'));
const empty=renderToStaticMarkup(React.createElement(LandingCoverage,{states:[states[0]],statesStatus:'ready',onRetryStates:()=>{}}));
assert.ok(empty.includes('Nenhum outro estado está habilitado'));
assert.ok(source.includes('<LandingCoverage states={states}'));
console.log('PASS: live coverage, PR without gov.br, other enabled states with gov.br, alphabetical list, loading/error/empty states.');
