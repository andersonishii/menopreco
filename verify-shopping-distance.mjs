import {registerHooks} from 'node:module';
registerHooks({resolve(s,c,n){return s.startsWith('.')&&!/\.[a-z]+$/i.test(s)?n(s+'.ts',c):n(s,c)}});
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {stripTypeScriptTypes} from 'node:module';
import {offerPrice,discountOrder} from './lib/offer-price.ts';
const {distancePriceOrder,distanceToleranceOrder}=await import('./lib/product-groups.ts');
const source=stripTypeScriptTypes(fs.readFileSync('lib/shopping-price.ts','utf8')).replace(/^import .*;$/gm,'').replace(/export /g,'');
const choose=new Function('offerPrice','discountOrder','distancePriceOrder','distanceToleranceOrder',source+';return chooseShoppingOffer;')(offerPrice,discountOrder,distancePriceOrder,distanceToleranceOrder);
const code='7898024394938',now=new Date('2026-10-11T15:00:00Z');
const offer=(id,price,distance,date='2026-10-11T12:00:00Z')=>({id,gtin:code,desc:'Produto',valor_tabela:String(price),distkm:distance,datahora:date,tempo:'hoje',estabelecimento:{}});
const offers=[offer('farCheap',5,'3'),offer('near',20,'0.5'),offer('nearCheap',10,'0.504'),offer('missing',1,'')];
assert.equal(choose(offers,code,'distance',now).offer.id,'nearCheap');
assert.equal(choose([offer('oldNear',20,'0.1','2026-10-10T12:00:00Z'),offers[0]],code,'distance',now).offer.id,'oldNear');
assert.equal(choose([offers[3]],code,'distance',now),undefined);
assert.equal(choose(offers,code,'cheapest',now).offer.id,'missing');
assert.equal(choose([offer('oldCheap',1,'1','2026-10-10T12:00:00Z'),offers[0]],code,'recent',now).offer.id,'farCheap');
assert.equal(choose([offer('old',1,'1','2026-10-10T12:00:00Z')],code,'today',now),undefined);
assert.equal(choose(offers,'12345678','distance',now),undefined);
console.log('PASS: lista por distância, desempate por preço, datas, GTIN e critérios anteriores.');

const tolerant=[offer('closest',20,'2'),offer('bestNearby',10,'2.8'),offer('outside',1,'3.1')];
assert.equal(choose(tolerant,code,'distance',now,1).offer.id,'bestNearby');
assert.equal(choose(tolerant,code,'distance',now,0).offer.id,'closest');
assert.deepEqual(distanceToleranceOrder(tolerant,1).map(o=>o.id),['bestNearby','closest','outside']);
console.log('PASS: tolerância adicional, preço na faixa, exclusão de oferta além da faixa e zero sem tolerância.');

const samePrice=[offer('farLatest',5.98,'15.09','2026-10-11T14:00:00Z'),offer('nearEarlier',5.98,'2.5','2026-10-11T12:00:00Z')];
for(const policy of ['cheapest','today','recent','discount','distance'])assert.equal(choose(samePrice,code,policy,now).offer.id,'nearEarlier');
assert.equal(choose([offer('unknown',5.98,''),samePrice[1]],code,'recent',now).offer.id,'nearEarlier');
assert.equal(choose([offer('invalid',5.98,'NaN'),samePrice[1]],code,'recent',now).offer.id,'nearEarlier');
assert.equal(choose([offer('veryClose',5.98,'2.501','2026-10-11T12:00:00Z'),offer('slightlyFar',5.98,'2.504','2026-10-11T14:00:00Z')],code,'distance',now).offer.id,'veryClose');
assert.equal(choose(samePrice,code,'distance',now,20).offer.id,'nearEarlier');
console.log('PASS: preço igual prioriza menor distância antes da hora; distância ausente não vira zero.');
